  final String level; // A1, A2, B1, B2, C1, YDS
  final String exampleEn;
  final String exampleTr;
  final List<String> synonyms;
  final int box; // 1 to 5 (Leitner system)
  final bool isFavorite;
  final int correctCount;
  final int wrongCount;

  WordItem({
    required this.id,
    required this.word,
    required this.meaning,
    this.phonetic = '',
    required this.partOfSpeech,
    required this.level,
    required this.exampleEn,
    required this.exampleTr,
    this.synonyms = const [],
    this.box = 1,
    this.isFavorite = false,
    this.correctCount = 0,
    this.wrongCount = 0,
  });

  WordItem copyWith({
    int? box,
    bool? isFavorite,
    int? correctCount,
    int? wrongCount,
  }) {
    return WordItem(
      id: id,
      word: word,
      meaning: meaning,
      phonetic: phonetic,
      partOfSpeech: partOfSpeech,
      level: level,
      exampleEn: exampleEn,
      exampleTr: exampleTr,
      synonyms: synonyms,
      box: box ?? this.box,
      isFavorite: isFavorite ?? this.isFavorite,
      correctCount: correctCount ?? this.correctCount,
      wrongCount: wrongCount ?? this.wrongCount,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'word': word,
      'meaning': meaning,
      'phonetic': phonetic,
      'partOfSpeech': partOfSpeech,
      'level': level,
      'exampleEn': exampleEn,
      'exampleTr': exampleTr,
      'synonyms': synonyms,
      'box': box,
      'isFavorite': isFavorite,
      'correctCount': correctCount,
      'wrongCount': wrongCount,
    };
  }

  factory WordItem.fromMap(Map<String, dynamic> map) {
    return WordItem(
      id: map['id'] as String,
      word: map['word'] as String,
      meaning: map['meaning'] as String,
      phonetic: map['phonetic'] as String? ?? '',
      partOfSpeech: map['partOfSpeech'] as String? ?? 'noun',
      level: map['level'] as String? ?? 'A1',
      exampleEn: map['exampleEn'] as String? ?? '',
      exampleTr: map['exampleTr'] as String? ?? '',
      synonyms: List<String>.from(map['synonyms'] as List? ?? []),
      box: map['box'] as int? ?? 1,
      isFavorite: map['isFavorite'] as bool? ?? false,
      correctCount: map['correctCount'] as int? ?? 0,
      wrongCount: map['wrongCount'] as int? ?? 0,
    );
  }

  String toJson() => json.encode(toMap());
  factory WordItem.fromJson(String source) =>
      WordItem.fromMap(json.decode(source) as Map<String, dynamic>);

